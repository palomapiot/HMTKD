"""Stage I: pool the blind rationales of several teachers (multi-teacher distillation).

For every post in the shared pool:
    traces          up to --per_teacher accepted blind traces per teacher (best quality first)
    teacher_soft    label votes: per teacher, the share of its k first-round blind samples
                    voting each label, averaged over teachers (diagnostics only: teacher
                    accuracy and agreement; not a training target)
    agreement       share of teachers whose majority label equals the ensemble majority
    status          blind (>= 1 teacher accepted) / hinted / unresolved / failed

Only the first blind round is used for teacher_soft: blind_extra samples exist
only for posts a teacher already failed, so they would bias the distribution.

Posts no teacher solved blind are written to unresolved_uids.txt for one hinted
run (02_teacher_traces.py --rounds hinted --only_uids ...); rerun this script
with --hinted <that run's name> to add those traces.

Stdlib only:
    python3 scripts/02b_merge_teachers.py --teachers llama70b qwen38 gemma4 --pool_name pool-mhs
    python3 scripts/02b_merge_teachers.py --teachers llama70b qwen38 gemma4 --pool_name pool-mhs \
        --hinted hinted-qwen38
"""

import argparse
import json
import sys
from collections import Counter, defaultdict
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hmtkd import scoring, taxonomy as tx  # noqa: E402
from hmtkd.io import difficulty, read_jsonl, write_jsonl  # noqa: E402


def parse_arguments():
    p = argparse.ArgumentParser(description="Pool teacher rationales.")
    p.add_argument("--teachers", nargs="+", required=True, help="teacher run names under data/traces/")
    p.add_argument("--hinted", default=None, help="name of the hinted run, if any")
    p.add_argument("--out_name", default="pooled")
    p.add_argument("--per_teacher", type=int, default=1, help="max accepted traces kept per teacher and post")
    p.add_argument("--pool_name", default="pool", help="pool file prefix used by the teacher runs")
    p.add_argument("--data_dir", type=Path, default=ROOT / "data")
    return p.parse_args()


def load_candidates(run_dir, rounds):
    rows = []
    for rnd in rounds:
        path = run_dir / f"candidates_{rnd}.jsonl"
        if path.exists():
            rows += read_jsonl(path)
    return rows


def majority(dist):
    return max(dist, key=dist.get) if dist else None


def main():
    args = parse_arguments()
    traces_dir = args.data_dir / "traces"
    posts = []
    for split in ("train", "dev"):
        path = traces_dir / f"{args.pool_name}_{split}.jsonl"
        if not path.exists():
            sys.exit(f"❌ {path} not found: run scripts/02_teacher_traces.py first.")
        current = {r["uid"]: r for r in read_jsonl(args.data_dir / "processed" / f"{split}.jsonl")}
        posts += [current[r["uid"]] for r in read_jsonl(path) if r["uid"] in current]

    gold = {p["uid"]: p for p in posts}

    def rescore(c):
        """Re-parse the raw output and re-check it against the CURRENT annotation (parser and gold may have changed since generation)."""
        c["analysis"] = scoring.parse_analysis(c.get("raw")) if "raw" in c else c["analysis"]
        if c["analysis"] and c["uid"] in gold:
            c["scores"] = scoring.facet_scores(c["analysis"], gold[c["uid"]])
            c["accepted"], c["failed"] = scoring.accept(c["scores"], c["analysis"])
        return c

    # teacher -> uid -> candidates
    blind = {}
    for t in args.teachers:
        run_dir = traces_dir / t
        if not (run_dir / "candidates_blind.jsonl").exists():
            sys.exit(f"❌ {run_dir}/candidates_blind.jsonl not found.")
        by_uid = defaultdict(list)
        for c in load_candidates(run_dir, ["blind", "blind_extra"]):
            by_uid[c["uid"]].append(rescore(c))
        blind[t] = by_uid
    # only pool posts every teacher has finished (smoke tests, runs still in progress)
    done = set.intersection(*({c for c in blind[t]} for t in args.teachers))
    if len(done) < len(posts):
        print(f"⚠️  {len(posts) - len(done)} pool posts not generated by every teacher yet; skipped.")
    posts = [p for p in posts if p["uid"] in done]

    hinted = defaultdict(list)
    if args.hinted:
        for c in load_candidates(traces_dir / args.hinted, ["hinted"]):
            hinted[c["uid"]].append(rescore(c))

    out, unresolved = [], []
    for post in posts:
        uid = post["uid"]
        traces, per_teacher_soft = [], {}
        for t in args.teachers:
            cands = blind[t].get(uid, [])
            first = [c["analysis"]["label"] for c in cands if c["round"] == "blind" and c["analysis"]]
            if first:
                counts = Counter(first)
                per_teacher_soft[t] = {lbl: round(counts[lbl] / len(first), 4) for lbl in tx.LABELS}
            ok = sorted((c for c in cands if c["accepted"]),
                        key=lambda c: scoring.quality(c["scores"]), reverse=True)
            traces += [{"teacher": t, "round": c["round"], "analysis": c["analysis"],
                        "scores": c["scores"]} for c in ok[:args.per_teacher]]

        teacher_soft = None
        if per_teacher_soft:
            teacher_soft = {lbl: round(sum(d[lbl] for d in per_teacher_soft.values())
                                       / len(per_teacher_soft), 4) for lbl in tx.LABELS}
        ensemble = majority(teacher_soft)
        agreement = (sum(majority(d) == ensemble for d in per_teacher_soft.values())
                     / len(per_teacher_soft)) if per_teacher_soft else None

        status = "blind" if traces else "failed"
        if not traces:
            hint = [c for c in hinted.get(uid, []) if c["analysis"]]
            if hint:
                ok = [c for c in hint if c["accepted"]]
                best = max(ok or hint, key=lambda c: scoring.quality(c["scores"]))
                status = "hinted" if ok else "unresolved"
                traces = [{"teacher": args.hinted, "round": "hinted", "analysis": best["analysis"],
                           "scores": best["scores"]}]
            else:
                unresolved.append(uid)

        out.append({
            "uid": uid, "dataset": post["dataset"], "split": post["split"], "text": post["text"],
            "label_set": post["label_set"], "difficulty": difficulty(post),
            "status": status, "hinted": status in ("hinted", "unresolved"),
            "teachers_accepted": sorted({tr["teacher"] for tr in traces if tr["round"] != "hinted"}),
            "traces": traces,
            "teacher_soft": teacher_soft, "per_teacher_soft": per_teacher_soft,
            "teacher_agreement": None if agreement is None else round(agreement, 4),
        })

    out_dir = traces_dir / args.out_name
    out_dir.mkdir(parents=True, exist_ok=True)
    write_jsonl(out_dir / "traces.jsonl", out)
    (out_dir / "unresolved_uids.txt").write_text("\n".join(unresolved) + ("\n" if unresolved else ""))
    summary = summarise(args, out)
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))
    print(f"\n✅ {len(out)} posts -> {out_dir / 'traces.jsonl'}; "
          f"{len(unresolved)} unsolved by every teacher -> {out_dir / 'unresolved_uids.txt'}")


def summarise(args, rows):
    n = len(rows)

    def rate(pred, subset=rows):
        return round(sum(pred(r) for r in subset) / max(len(subset), 1), 4)

    def by(key):
        groups = defaultdict(list)
        for r in rows:
            groups[key(r)].append(r)
        return {k: {"n": len(g), "pooled_blind_rate": rate(lambda r: r["status"] == "blind", g),
                    **{f"{t}_blind_rate": rate(lambda r, t=t: t in r["teachers_accepted"], g)
                       for t in args.teachers}}
                for k, g in sorted(groups.items())}

    # label accuracy of each teacher's majority vote, and of the ensemble, against the gold set
    accuracy = {t: rate(lambda r, t=t: majority(r["per_teacher_soft"].get(t)) in r["label_set"],
                        [r for r in rows if t in r["per_teacher_soft"]]) for t in args.teachers}
    accuracy["ensemble"] = rate(lambda r: majority(r["teacher_soft"]) in r["label_set"],
                                [r for r in rows if r["teacher_soft"]])
    accuracy_by_dataset = {
        ds: {t: rate(lambda r, t=t: majority(r["per_teacher_soft"].get(t)) in r["label_set"],
                     [r for r in rows if r["dataset"] == ds and t in r["per_teacher_soft"]])
             for t in args.teachers}
        for ds in sorted({r["dataset"] for r in rows})}

    pairwise = {}
    for a, b in combinations(args.teachers, 2):
        both = [r for r in rows if a in r["per_teacher_soft"] and b in r["per_teacher_soft"]]
        pairwise[f"{a}~{b}"] = rate(lambda r: majority(r["per_teacher_soft"][a])
                                    == majority(r["per_teacher_soft"][b]), both)

    return {
        "teachers": args.teachers, "hinted_run": args.hinted, "per_teacher": args.per_teacher,
        "n_posts": n,
        "status": dict(Counter(r["status"] for r in rows)),
        "blind_rate": {**{t: rate(lambda r, t=t: t in r["teachers_accepted"]) for t in args.teachers},
                       "pooled": rate(lambda r: r["status"] == "blind")},
        "n_teachers_accepted": dict(sorted(Counter(len(r["teachers_accepted"]) for r in rows).items())),
        "traces_per_post": dict(sorted(Counter(len(r["traces"]) for r in rows).items())),
        "majority_label_accuracy": accuracy,
        "majority_label_accuracy_by_dataset": accuracy_by_dataset,
        "pairwise_majority_agreement": pairwise,
        "by_dataset": by(lambda r: r["dataset"]),
        "by_difficulty": by(lambda r: r["difficulty"]),
        "by_label_set": by(lambda r: "|".join(r["label_set"])),
    }


if __name__ == "__main__":
    main()
